"""Download one file of a registered dataset from the first working host.

Hosts are tried in the given order (sorted by priority) until one succeeds. `kind: file` hosts are fetched over
HTTP(S) (resuming partial downloads) or copied from file:// URLs. `kind: api` hosts
are fetched by the `fetch(request: DownloadRequest) -> dict` function of their handler
module, which writes the file to `request.destination` and returns extra provenance.

Each downloaded file is verified (HTTP errors, unexpected HTML pages, empty files)
before being moved to its final location, and a provenance file is written next to it.

See `meta.yaml` for the expected inputs, params and configuration.
"""

import hashlib
import importlib.util
import logging
import os
import re
import shutil
import string
import sys
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from types import ModuleType
from typing import TYPE_CHECKING, Any
from urllib.parse import urlparse
from urllib.request import url2pathname

import requests
import yaml
from requests.adapters import HTTPAdapter
from urllib3.util import Retry

if TYPE_CHECKING:
    snakemake: Any

LOGGER = logging.getLogger(__name__)
CHUNK_SIZE = 1024 * 1024
RETRY_STATUS_CODES = {408, 429, 500, 502, 503, 504}
STREAM_EXCEPTIONS = (
    requests.exceptions.ConnectionError,
    requests.exceptions.Timeout,
    requests.exceptions.ChunkedEncodingError,
)


class HostError(Exception):
    """A host could not provide a valid file."""


@dataclass
class DownloadTimeouts:
    """Timeout and retry settings for download requests."""

    max_retries: int
    connect_seconds: int
    read_seconds: int
    initial_retry_seconds: int

    @property
    def request_timeout(self) -> tuple[int, int]:
        """Connect and read timeouts, as expected by `requests`."""
        return (self.connect_seconds, self.read_seconds)

    @property
    def retry(self) -> Retry:
        """Retry transient connection failures and status codes, with exponential backoff.

        `Retry-After` headers are respected. The final response is returned as-is.
        """
        return Retry(
            total=self.max_retries,
            backoff_factor=self.initial_retry_seconds,
            backoff_max=60,
            status_forcelist=RETRY_STATUS_CODES,
            allowed_methods={"GET"},
            raise_on_status=False,
        )


@dataclass
class DownloadRequest:
    """One file to fetch from one host."""

    host: dict
    url: str
    version: str
    placeholders: dict[str, str]
    destination: Path
    session: requests.Session
    timeouts: DownloadTimeouts

    def secret(self, extra: str) -> str:
        """Read a secret from the environment variable named by a host extra."""
        name = self.host["extras"][extra]
        if name not in os.environ:
            raise HostError(
                f"Environment variable {name!r} (host extra {extra!r}) is not set."
            )
        return os.environ[name]

    def get(self, url: str, **kwargs) -> requests.Response:
        """GET a URL with the request timeouts, retrying transient failures.

        The final response is returned as-is: callers must check its status.
        """
        return self.session.get(url, timeout=self.timeouts.request_timeout, **kwargs)


Fetcher = Callable[[DownloadRequest], dict]


def file_regex(template: str, version: str) -> str:
    """Build a regex with named groups matching file names generated by a template."""
    regex = ""
    seen = set()
    for literal, field, _, _ in string.Formatter().parse(template):
        regex += re.escape(literal)
        if not field:
            continue
        if field == "version":
            regex += re.escape(version)
        elif field in seen:
            regex += f"(?P={field})"
        else:
            regex += f"(?P<{field}>[^/]+?)"
            seen.add(field)
    return regex


def match_file(templates: list[str], version: str, file: str) -> dict[str, str]:
    """Find the file template matching a file name and return its placeholder values."""
    for template in templates:
        if match := re.fullmatch(file_regex(template, version), file):
            return match.groupdict()
    raise ValueError(f"File {file!r} does not match any registered file: {templates}.")


def reject_html(response: requests.Response, filename: str) -> None:
    """Avoid saving error pages served with a successful status code."""
    content_type = response.headers.get("Content-Type", "").lower()
    if "text/html" in content_type and not filename.endswith((".html", ".htm")):
        raise HostError(f"Received an HTML page instead of {filename!r}.")


def fetch_file(request: DownloadRequest) -> dict:
    """Fetch a file over HTTP(S) or copy it from a file:// URL.

    HTTP downloads are resumed if the destination already holds a partial download
    or if the connection drops while streaming.
    """
    url, destination, timeouts = request.url, request.destination, request.timeouts
    parsed = urlparse(url)
    if parsed.scheme == "file":
        source = Path(url2pathname(parsed.path))
        if not source.is_file():
            raise HostError(f"File not found: {source}.")
        shutil.copyfile(source, destination)
        return {}
    if parsed.scheme not in {"http", "https"}:
        raise HostError(f"Unsupported URL scheme {parsed.scheme!r}.")

    for attempt in range(timeouts.max_retries + 1):
        existing = destination.stat().st_size if destination.exists() else 0
        headers = {"Range": f"bytes={existing}-"} if existing else {}
        with request.get(url, headers=headers, stream=True) as response:
            if response.status_code == 416:
                destination.unlink()
                continue
            if response.status_code >= 400:
                raise HostError(f"HTTP {response.status_code} for {url!r}.")
            reject_html(response, destination.name.removesuffix(".part"))
            mode = "ab" if response.status_code == 206 else "wb"
            try:
                with destination.open(mode) as f:
                    for chunk in response.iter_content(CHUNK_SIZE):
                        f.write(chunk)
            except STREAM_EXCEPTIONS as exc:
                if attempt == timeouts.max_retries:
                    raise HostError(f"Download interrupted for {url!r}.") from exc
                LOGGER.warning("Download interrupted, resuming (%s).", exc)
                continue
        return {}
    raise HostError(f"Could not download {url!r}.")


def load_fetcher(host: dict) -> Fetcher:
    """Get the fetch function of a host: built-in for files, from its handler for APIs."""
    if host["kind"] == "file":
        return fetch_file
    path = Path(host["handler"])
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module: ModuleType = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.fetch


def verify_file(path: Path, expected: str | None) -> str:
    """Check that a file is non-empty and matches its SHA-256 checksum, if expected."""
    if not path.exists() or path.stat().st_size == 0:
        raise HostError("Downloaded file is empty.")
    with path.open("rb") as f:
        digest = hashlib.file_digest(f, "sha256").hexdigest()
    if expected is not None and digest != expected:
        raise HostError(f"Checksum mismatch: expected {expected}, got {digest}.")
    return digest


def download(
    dataset: str,
    version: str,
    file: str,
    spec: dict,
    hosts: list[dict],
    settings: dict,
    output_path: Path,
    provenance_path: Path,
) -> None:
    """Download a file from the first working host and record its provenance."""
    placeholders = match_file(spec["files"], version, file)
    timeouts = DownloadTimeouts(**settings["timeouts"])
    session = requests.Session()
    session.headers["User-Agent"] = settings["user_agent"]
    adapter = HTTPAdapter(max_retries=timeouts.retry)
    session.mount("http://", adapter)
    session.mount("https://", adapter)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    partial = output_path.with_name(output_path.name + ".part")
    errors = []
    for host in hosts:
        url = host["url"].format(version=version, file=file, **placeholders)
        LOGGER.info("Trying host %r: %s", host["name"], url)
        request = DownloadRequest(
            host, url, version, placeholders, partial, session, timeouts
        )
        fetch = load_fetcher(host)
        try:
            metadata = fetch(request)
            digest = verify_file(partial, spec["sha256"].get(file))
        except Exception as exc:
            LOGGER.warning("Host %r failed: %s", host["name"], exc)
            errors.append(f"- {host['name']} ({url}): {exc}")
            partial.unlink(missing_ok=True)
            continue
        os.replace(partial, output_path)
        break
    else:
        raise RuntimeError(
            f"Could not download {file!r} of {dataset!r} version {version!r}:\n"
            + "\n".join(errors)
        )

    provenance = {
        "dataset": dataset,
        "version": version,
        "file": file,
        "host": host["name"],
        "url": url,
        "retrieved_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "sha256": digest,
        "size_bytes": output_path.stat().st_size,
        "license": spec["license"],
        "tags": spec["tags"],
        "note": spec["note"],
        **metadata,
    }
    provenance_path.write_text(
        yaml.safe_dump(provenance, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    LOGGER.info("Downloaded %s from %r.", output_path, host["name"])


if __name__ == "__main__":
    sys.stderr = open(snakemake.log[0], "w")
    logging.basicConfig(stream=sys.stderr, level=logging.INFO)
    resolved = snakemake.config["_downloads"]
    dataset = snakemake.params.dataset
    version = snakemake.wildcards.version
    download(
        dataset=dataset,
        version=version,
        file=snakemake.wildcards.file,
        spec=snakemake.params.spec,
        hosts=resolved["hosts"][dataset][version],
        settings=resolved["settings"],
        output_path=Path(snakemake.output.path),
        provenance_path=Path(snakemake.output.provenance),
    )
